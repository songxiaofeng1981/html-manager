function pick() {
  const ui = (globalThis.chrome?.i18n?.getUILanguage?.() || navigator.language || 'en').toLowerCase();
  return ui.startsWith('zh') ? 'zh' : 'en';
}

export const lang = new URLSearchParams(location.search).get('lang') || pick();
const dict = lang === 'zh' ? zh : en;

export function t(key, ...args) {
  const v = dict[key] ?? en[key];
  if (v == null) {
    console.warn('missing text', key);
    return key;
  }
  return typeof v === 'function' ? v(...args) : v;
}

/** Fills elements marked data-i18n (text), data-i18n-title, data-i18n-label (aria-label), data-i18n-placeholder. */
export function localizePage() {
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of document.querySelectorAll('[data-i18n-label]')) el.setAttribute('aria-label', t(el.dataset.i18nLabel));
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const list of document.querySelectorAll('[data-keys]')) {
    list.replaceChildren();
    for (const line of t(list.dataset.keys).split('|')) {
      const [k, v] = line.split('=');
      const row = document.createElement('div');
      row.append(document.createElement('kbd'), document.createElement('span'));
      row.firstChild.textContent = k;
      row.lastChild.textContent = v;
      list.append(row);
    }
  }
}

